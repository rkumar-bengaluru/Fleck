"""Write web/src/events.ts from the pydantic event models (no npm needed).

Handles only what the models use: scalars, const/enum literals, arrays, nullable, $ref, anyOf.
"""
import sys
from pathlib import Path

from pydantic import TypeAdapter

from fleck_core.events import Event

OUT = Path(__file__).resolve().parent.parent / "web/src/events.ts"
SCALARS = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}


def ts(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "const" in s:
        return repr(s["const"]).replace("'", '"')
    if "enum" in s:
        return " | ".join('"%s"' % v for v in s["enum"])
    if "anyOf" in s:
        return " | ".join(ts(x) for x in s["anyOf"])
    t = s.get("type")
    if t == "array":
        inner = ts(s["items"])
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t in SCALARS:
        return SCALARS[t]
    raise ValueError(f"unsupported schema: {s}")


def main() -> None:
    schema = TypeAdapter(Event).json_schema(mode="serialization")
    out = ["// Generated by scripts/gen_event_types.py (make gen-types). Do not edit.\n"]
    for name, d in schema["$defs"].items():
        req = set(d.get("required", []))
        out.append(f"export interface {name} {{")
        for p, s in d["properties"].items():
            out.append(f"  {p}{'' if p in req else '?'}: {ts(s)};")
        out.append("}\n")
    names = [r["$ref"].rsplit("/", 1)[-1] for r in schema["oneOf"]]
    out.append(f"export type FleckEvent = {' | '.join(names)};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    sys.exit(main())
